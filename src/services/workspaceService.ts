/**
 * Google Workspace Service for Google Drive & Gmail
 * Interacts directly with Drive & Gmail REST APIs using client OAuth tokens
 */

export interface DriveSaveResult {
  fileId: string;
  fileName: string;
  webViewLink?: string;
}

export interface GmailSendResult {
  messageId: string;
  threadId: string;
}

/**
 * Saves research analysis markdown document into user's Google Drive
 */
export async function saveAnalysisToGoogleDrive(
  token: string,
  fileName: string,
  content: string
): Promise<DriveSaveResult> {
  const metadata = {
    name: fileName.endsWith('.md') ? fileName : `${fileName}.md`,
    mimeType: 'text/markdown',
    description: 'Generated by Research Paper Intelligence',
  };

  const boundary = '-------314159265358979323846';
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    'Content-Type: text/markdown; charset=UTF-8\r\n\r\n' +
    content +
    closeDelimiter;

  const response = await fetch('https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,webViewLink', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': `multipart/related; boundary=${boundary}`,
    },
    body: multipartRequestBody,
  });

  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(`Google Drive API error (${response.status}): ${errorBody}`);
  }

  const data = await response.json();
  return {
    fileId: data.id,
    fileName: data.name,
    webViewLink: data.webViewLink,
  };
}

/**
 * Sends research briefing email via Gmail REST API
 */
export async function sendBriefingViaGmail(
  token: string,
  to: string,
  subject: string,
  bodyHtml: string
): Promise<GmailSendResult> {
  // RFC 2822 formatting
  const utf8Subject = `=?utf-8?B?${btoa(unescape(encodeURIComponent(subject)))}?=`;
  const emailLines = [
    `To: ${to}`,
    'Content-Type: text/html; charset=utf-8',
    'MIME-Version: 1.0',
    `Subject: ${utf8Subject}`,
    '',
    bodyHtml,
  ];
  const emailRaw = emailLines.join('\r\n');

  // Base64url encoding
  const base64Encoded = btoa(unescape(encodeURIComponent(emailRaw)))
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');

  const response = await fetch('https://gmail.googleapis.com/gmail/v1/users/me/messages/send', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ raw: base64Encoded }),
  });

  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(`Gmail API error (${response.status}): ${errorBody}`);
  }

  const data = await response.json();
  return {
    messageId: data.id,
    threadId: data.threadId,
  };
}

export interface GoogleChatSpace {
  name: string;
  displayName: string;
  type?: string;
}

/**
 * Lists user's Google Chat spaces
 */
export async function listGoogleChatSpaces(token: string): Promise<GoogleChatSpace[]> {
  const response = await fetch('https://chat.googleapis.com/v1/spaces', {
    headers: {
      Authorization: `Bearer ${token}`,
      'Accept': 'application/json',
    },
  });

  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(`Google Chat API error (${response.status}): ${errorBody}`);
  }

  const data = await response.json();
  return (data.spaces || []).map((s: any) => ({
    name: s.name,
    displayName: s.displayName || s.name.replace('spaces/', 'Research Space '),
    type: s.type,
  }));
}

/**
 * Sends a message into a Google Chat space
 */
export async function sendGoogleChatMessage(
  token: string,
  spaceName: string,
  text: string
): Promise<{ messageId: string }> {
  const formattedSpace = spaceName.startsWith('spaces/') ? spaceName : `spaces/${spaceName}`;
  const response = await fetch(`https://chat.googleapis.com/v1/${formattedSpace}/messages`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ text }),
  });

  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(`Google Chat send error (${response.status}): ${errorBody}`);
  }

  const data = await response.json();
  return {
    messageId: data.name || data.id,
  };
}

